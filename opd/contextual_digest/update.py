from __future__ import annotations

from dataclasses import asdict
from collections import defaultdict

import torch
import torch.distributed as dist

from .losses import relay_token_losses
from .meta import gradient_dot, normalize_weights, relative_advantages, segment_alignments, task_policy_loss, weighted_token_sum


class MetaHandoffUpdater:
    def __init__(self, student, teacher, optimizer, config, distributed=False):
        self.student, self.teacher, self.optimizer = student, teacher, optimizer
        self.config, self.distributed = config, distributed
        self.parameters = tuple(p for p in student.model.parameters() if p.requires_grad)
        if not self.parameters:
            raise ValueError("No trainable student parameters")
        self.device = self.parameters[0].device
        teacher_parameters = list(teacher.model.parameters())
        self.teacher_versions = tuple(p._version for p in teacher_parameters)
        if any(p.requires_grad for p in teacher_parameters):
            raise ValueError("Teacher must be frozen before constructing the updater")
        if {id(p) for group in optimizer.param_groups for p in group["params"]} & {id(p) for p in teacher_parameters}:
            raise ValueError("Teacher parameters must never enter the optimizer")

    def _sum(self, value):
        value = torch.as_tensor(value, device=self.device, dtype=torch.float64).clone()
        if self.distributed:
            dist.all_reduce(value, op=dist.ReduceOp.SUM)
        return value

    def _task_gradients(self, tasks):
        grouped = defaultdict(list)
        for trace, reward in tasks:
            trace.validate()
            if any(x != "student" for x in trace.sources) or trace.summary_spans or trace.handoffs:
                raise ValueError("Meta task answers must be generated by the student independently")
            grouped[trace.question_id].append((trace, reward))
        if any(len(group) != self.config.meta.task_samples for group in grouped.values()):
            raise ValueError("Each independent task question needs exactly task_samples answers")
        count = self._sum(len(tasks))
        if count <= 0:
            raise ValueError("An enabled meta update needs independently sampled task answers")
        result = [torch.zeros_like(p) for p in self.parameters]
        informative, reward_sum = 0, 0.0
        for group in grouped.values():
            rewards = torch.tensor([[float(r) for _, r in group]], device=self.device)
            advantages = relative_advantages(rewards)[0]
            informative += int(bool((advantages != 0).any()))
            reward_sum += float(rewards.sum())
            for (trace, _), advantage in zip(group, advantages, strict=True):
                if advantage == 0:
                    continue
                lp = self.student.log_probs(trace.prompt_ids, trace.response_ids, grad=True)
                loss = task_policy_loss(lp, advantage) / count
                gradients = torch.autograd.grad(loss, self.parameters, allow_unused=True)
                for target, gradient in zip(result, gradients, strict=True):
                    if gradient is not None:
                        target.add_(gradient.detach())
                del lp, loss, gradients
        if self.distributed:
            for gradient in result:
                dist.all_reduce(gradient, op=dist.ReduceOp.SUM)
        return tuple(result), {
            "task_responses": int(count), "task_informative_questions": int(self._sum(informative)),
            "task_reward_mean": float(self._sum(reward_sum) / count),
            "task_gradient_norm": float(gradient_dot(result, result).sqrt()),
        }

    def update(self, handoff, tasks):
        if not handoff:
            raise ValueError("Each rank needs a nonempty handoff batch")
        if {x.question_id for x in handoff} & {x.question_id for x, _ in tasks}:
            raise ValueError("Handoff and independent-task questions overlap")

        for trace in handoff:
            trace.validate()
        versions = tuple(p._version for p in self.parameters)
        self.optimizer.zero_grad(set_to_none=True)
        if self.config.meta.enabled:
            task_gradients, metrics = self._task_gradients(tasks)
        else:
            if tasks:
                raise ValueError("Meta-disabled updates should not consume an unused task batch")
            task_gradients, metrics = (), {"task_responses": 0, "task_informative_questions": 0}

        scored, scores, lengths = [], [], []
        for trace in handoff:


            old = self.student.log_probs(trace.prompt_ids, trace.response_ids, grad=False).detach().cpu()
            teacher = self.teacher.log_probs(trace.prompt_ids, trace.response_ids, grad=False).detach().cpu()
            scored.append((trace, old, teacher))
            lengths.extend(span.end - span.start for span in trace.summary_spans)
            if not trace.summary_spans:
                continue
            if self.config.meta.enabled and metrics["task_gradient_norm"] == 0:


                scores.extend(torch.zeros((), device=self.device, dtype=torch.float64) for _ in trace.summary_spans)
            elif self.config.meta.enabled:
                lp = self.student.log_probs(trace.prompt_ids, trace.response_ids, grad=True)
                losses = relay_token_losses(lp, old.to(self.device), teacher.to(self.device), self.config.clip_ratio)
                scores.extend(segment_alignments(losses, trace.summary_spans, self.parameters, task_gradients).unbind())
                del lp, losses
            else:
                scores.extend(torch.ones((), device=self.device, dtype=torch.float64) for _ in trace.summary_spans)
        del task_gradients
        alignments = torch.stack(scores) if scores else torch.empty(0, device=self.device, dtype=torch.float64)
        lengths_tensor = torch.tensor(lengths, device=self.device, dtype=torch.float64)
        normalized = normalize_weights(alignments, lengths_tensor, self.distributed,
                                       strength=self.config.meta.weight_strength)
        if versions != tuple(p._version for p in self.parameters):
            raise RuntimeError("Student parameters changed before the single final update")
        if any(p.grad is not None for p in self.parameters):
            raise RuntimeError("Meta-only gradients leaked into optimizer gradient buffers")
        denominator = self._sum(sum(len(trace.response_ids) for trace in handoff))
        if denominator <= 0:
            raise ValueError("Empty OPD response batch")
        cursor, local_loss, audits = 0, 0.0, []
        for trace, old, teacher in scored:
            size = len(trace.summary_spans)
            weights = normalized.weights[cursor:cursor + size]
            lp = self.student.log_probs(trace.prompt_ids, trace.response_ids, grad=True)
            losses = relay_token_losses(lp, old.to(self.device), teacher.to(self.device), self.config.clip_ratio)


            loss = weighted_token_sum(losses, trace.summary_spans, weights) / denominator
            local_loss += float(loss.detach())
            loss.backward()
            audits.append({
                "question_id": trace.question_id,
                "segments": [
                    {**asdict(span), "alignment": float(a), "raw_weight": float(raw), "weight": float(w)}
                    for span, a, raw, w in zip(trace.summary_spans, alignments[cursor:cursor + size],
                        normalized.raw_weights[cursor:cursor + size], weights, strict=True)
                ],
            })
            cursor += size
            del lp, losses, loss
        if self.distributed:
            for parameter in self.parameters:
                if parameter.grad is None:
                    parameter.grad = torch.zeros_like(parameter)
                dist.all_reduce(parameter.grad, op=dist.ReduceOp.SUM)
        norm = torch.nn.utils.clip_grad_norm_(self.parameters, self.config.max_grad_norm, error_if_nonfinite=True)
        clipped_norm = torch.linalg.vector_norm(torch.stack([
            p.grad.detach().norm(2) for p in self.parameters if p.grad is not None
        ]))
        if not torch.isfinite(clipped_norm) or clipped_norm > self.config.max_grad_norm * (1 + 1e-5):
            raise FloatingPointError("Final Student gradient clipping failed")
        self.optimizer.step()
        self.optimizer.zero_grad(set_to_none=True)
        if any(p.grad is not None or p.requires_grad for p in self.teacher.model.parameters()):
            raise RuntimeError("Teacher is not frozen")
        if self.teacher_versions != tuple(p._version for p in self.teacher.model.parameters()):
            raise RuntimeError("Frozen Teacher parameters changed in place")
        weight_lists = [normalized.weights.cpu().tolist()]
        if self.distributed:
            gathered = [None] * dist.get_world_size()
            dist.all_gather_object(gathered, weight_lists[0])
            weight_lists = gathered
        all_weights = torch.tensor([w for values in weight_lists for w in values], dtype=torch.float64)
        raw_max = normalized.raw_weights.max() if normalized.raw_weights.numel() else alignments.new_zeros(())
        if self.distributed:
            dist.all_reduce(raw_max, op=dist.ReduceOp.MAX)

        raw_spread = self._sum((lengths_tensor * (normalized.raw_weights - 1).square()).sum())
        effective_spread = self._sum((lengths_tensor * (normalized.weights - 1).square()).sum())
        for source in ("student", "teacher", "summary"):
            count, k1_sum = 0, 0.0
            for trace, old, teacher_lp in scored:
                mask = torch.tensor([x == source for x in trace.sources])
                count += int(mask.sum())
                k1_sum += float((old - teacher_lp)[mask].double().sum())
            count = int(self._sum(count))
            metrics[f"{source}_tokens"] = count
            metrics[f"{source}_sampled_k1_mean"] = float(self._sum(k1_sum)) / count if count else 0.0
        metrics.update({
            "opd_loss": float(self._sum(local_loss)), "gradient_norm_before_clip": float(norm),
            "gradient_norm_after_clip": float(clipped_norm),
            "response_tokens": int(denominator), "summary_tokens": normalized.summary_tokens,
            "summary_segments": int(self._sum(len(scores))), "meta_equal_weight_fallback": normalized.fallback,
            "positive_alignment_segments": int(self._sum(int((alignments > 0).sum()))),
            "summary_weighted_token_sum": float(self._sum((lengths_tensor * normalized.weights).sum())),
            "meta_weight_strength": self.config.meta.weight_strength,
            "summary_raw_weight_max": float(raw_max),
            "summary_raw_weight_rms_from_one": float((raw_spread / normalized.summary_tokens).sqrt())
                if normalized.summary_tokens else 0.0,
            "summary_weight_rms_from_one": float((effective_spread / normalized.summary_tokens).sqrt())
                if normalized.summary_tokens else 0.0,
            "summary_token_fraction": normalized.summary_tokens / float(denominator),
            "student_optimizer_steps": 1, "teacher_optimizer_steps": 0,
            "teacher_parameters_unchanged": True,
            "summary_weight_min": float(all_weights.min()) if all_weights.numel() else 0.0,
            "summary_weight_max": float(all_weights.max()) if all_weights.numel() else 0.0,
            "summary_weight_p95": float(all_weights.quantile(0.95)) if all_weights.numel() else 0.0,
            "zero_weight_segments": int((all_weights == 0).sum()),
        })
        return metrics, audits
